DROP POLICY IF EXISTS "listing_handoff_reviews_insert_own" ON public.listing_handoff_reviews;
CREATE POLICY "listing_handoff_reviews_insert_own"
  ON public.listing_handoff_reviews FOR INSERT
  TO authenticated
  WITH CHECK (
    reviewer_user_id = auth.uid()
    AND EXISTS (
      SELECT 1 FROM public.listing_handoffs lh
      WHERE lh.id = listing_handoff_reviews.handoff_id
        AND lh.status = 'COMPLETED'
        AND (
          (lh.owner_user_id = auth.uid() AND listing_handoff_reviews.reviewee_user_id = lh.recipient_user_id)
          OR
          (lh.recipient_user_id = auth.uid() AND listing_handoff_reviews.reviewee_user_id = lh.owner_user_id)
        )
    )
  );

DROP POLICY IF EXISTS "listing_handoff_reviews_update_own" ON public.listing_handoff_reviews;
CREATE POLICY "listing_handoff_reviews_update_own"
  ON public.listing_handoff_reviews FOR UPDATE
  TO authenticated
  USING (reviewer_user_id = auth.uid())
  WITH CHECK (reviewer_user_id = auth.uid());

CREATE INDEX IF NOT EXISTS idx_listing_handoffs_owner ON public.listing_handoffs(owner_user_id);
CREATE INDEX IF NOT EXISTS idx_listing_handoffs_recipient ON public.listing_handoffs(recipient_user_id);
CREATE INDEX IF NOT EXISTS idx_listing_handoffs_status ON public.listing_handoffs(status);
CREATE INDEX IF NOT EXISTS idx_listing_handoff_reviews_handoff_id ON public.listing_handoff_reviews(handoff_id);
CREATE INDEX IF NOT EXISTS idx_listing_handoff_reviews_reviewee ON public.listing_handoff_reviews(reviewee_user_id);

COMMIT;
