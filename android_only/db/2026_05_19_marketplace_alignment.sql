        RAISE EXCEPTION 'Store order owner must match listing store owner';
    END IF;

    IF NEW.amount <> v_sale_price OR NEW.currency_code <> v_currency THEN
        RAISE EXCEPTION 'Store order pricing must match the listing price';
    END IF;

    RETURN NEW;
END;
$$;

